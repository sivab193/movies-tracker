import { readFile, writeFile, mkdir } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import sharp from "sharp"

// The SVG masters contain only vector paths, including the supplied lettering.
const root = fileURLToPath(new URL("../", import.meta.url))
const brandDir = `${root}public/brand/`
const logo = await readFile(`${brandDir}logo-art.svg`, "utf8")
const mark = await readFile(`${brandDir}mark-art.svg`, "utf8")
const themedMark = (theme) => mark.replaceAll("var(--brand-rim, #fff)", theme === "dark" ? "#fff" : "#262626")
const themedLogo = (theme) => logo.replace('<!-- BRAND_RIM -->', `<path d="${silhouette}" fill="${theme === "dark" ? "#fff" : "#262626"}" stroke="${theme === "dark" ? "#fff" : "#262626"}" stroke-width="5" stroke-linejoin="round"/>`)
const silhouette = /<!-- SILHOUETTE (.*?) -->/.exec(logo)?.[1]
if (!silhouette) throw new Error("Logo master is missing its silhouette")

for (const theme of ["light", "dark"]) {
  await writeFile(`${brandDir}logo-${theme}.svg`, themedLogo(theme))
  await writeFile(`${brandDir}mark-${theme}.svg`, themedMark(theme))
}
await writeFile(`${brandDir}logo.svg`, themedLogo("dark"))
await writeFile(`${brandDir}mark.svg`, themedMark("dark"))

const svgBuffer = (svg) => Buffer.from(svg)
const png = (svg, size) => sharp(svgBuffer(svg), { density: 192 }).resize(size, size, { fit: "contain" }).png().toBuffer()
const appIcon = (maskable = false) => {
  const inset = maskable ? 28 : 12
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 192 192"><rect width="192" height="192" rx="${maskable ? 0 : 36}" fill="#171717"/><g transform="translate(${inset} ${inset}) scale(${(192-inset*2)/144})">${themedMark("dark").replace(/<\/?svg[^>]*>/g, "")}</g></svg>`
}
// Keep legacy asset URLs valid for older installed clients and external links.
await writeFile(`${root}public/favicon.svg`, themedMark("dark").replace('<title>', '<style>@media(prefers-color-scheme:light){.brand-rim{stroke:#262626}}</style><title>').replace('stroke="#fff" stroke-width="10"', 'class="brand-rim" stroke="#fff" stroke-width="10"'))
await writeFile(`${root}public/icon.svg`, appIcon())
for (const size of [192, 512]) {
  await writeFile(`${root}public/icon-${size}.svg`, appIcon())
  await writeFile(`${root}public/web-app-manifest-${size}x${size}.png`, await png(appIcon(), size))
  await writeFile(`${root}public/brand/icon-maskable-${size}.png`, await png(appIcon(true), size))
}
for (const [name, size, svg] of [
  ["favicon-96x96.png", 96, themedMark("dark")],
  ["apple-touch-icon.png", 180, appIcon()],
  ["apple-icon.png", 180, appIcon()],
  ["icon-light-32x32.png", 32, themedMark("light")],
  ["icon-dark-32x32.png", 32, themedMark("dark")],
  ["placeholder-logo.png", 256, themedLogo("dark")],
]) await writeFile(`${root}public/${name}`, await png(svg, size))
await writeFile(`${root}public/placeholder-logo.svg`, themedLogo("dark"))

// ICO containers can hold PNGs; include native small sizes for browser tab clarity.
const icoSizes = [16, 32, 48]
const icoPngs = await Promise.all(icoSizes.map(size => png(themedMark("dark"), size)))
const header = Buffer.alloc(6 + 16 * icoSizes.length)
header.writeUInt16LE(1, 2); header.writeUInt16LE(icoSizes.length, 4)
let offset = header.length
icoPngs.forEach((buffer, i) => {
  const entry = 6 + i * 16
  header[entry] = icoSizes[i]; header[entry + 1] = icoSizes[i]
  header.writeUInt16LE(1, entry + 4); header.writeUInt16LE(32, entry + 6)
  header.writeUInt32LE(buffer.length, entry + 8); header.writeUInt32LE(offset, entry + 12)
  offset += buffer.length
})
await writeFile(`${root}public/favicon.ico`, Buffer.concat([header, ...icoPngs]))

// Embed assets into edge-safe OG templates: no filesystem reads or logo fetches at request time.
await mkdir(`${root}lib/brand`, { recursive: true })
const logoPng = await sharp(svgBuffer(themedLogo("dark")), { density: 96 }).resize({ height: 420 }).png().toBuffer()
const markPng = await png(themedMark("dark"), 144)
await writeFile(`${root}lib/brand/generated.ts`, `// Generated by npm run brand:generate. Do not edit by hand.\nexport const BRAND_LOGO_DATA_URI = "data:image/png;base64,${logoPng.toString("base64")}"\nexport const BRAND_MARK_DATA_URI = "data:image/png;base64,${markPng.toString("base64")}"\n`)
console.log("Generated theme SVGs, browser/PWA icons, and embedded OG branding.")

// Review sheet: identical artwork on both app surfaces and at small icon sizes.
await mkdir(`${root}../docs/branding`, { recursive: true })
const uri = n => 'data:image/svg+xml;base64,'+Buffer.from(n.startsWith('logo') ? themedLogo(n.endsWith('dark') ? 'dark' : 'light') : themedMark(n.endsWith('dark') ? 'dark' : 'light')).toString('base64')
const panels = ['light','dark'].map((theme,i)=>{
const x=i*600; const dark=theme==='dark'; const fg=dark?'#fafafa':'#262626'; const muted=dark?'#b5b5b5':'#606060'
return `<g><rect x="${x}" width="600" height="800" fill="${dark?'#171717':'#f7f7f7'}"/><text x="${x+40}" y="54" fill="${muted}" font-family="sans-serif" font-size="18">${theme==='dark'?'Dark':'Light'} mode</text><image href="${uri('mark-'+theme)}" x="${x+40}" y="86" width="44" height="44"/><text x="${x+96}" y="116" fill="${fg}" font-family="sans-serif" font-size="24" font-weight="700">MediaVerse</text><path d="M${x+40} 154H${x+560}" stroke="${dark?'#3b3b3b':'#dedede'}"/><image href="${uri('logo-'+theme)}" x="${x+128}" y="204" width="344" height="382"/><text x="${x+40}" y="674" fill="${muted}" font-family="sans-serif" font-size="17">Browser / app mark</text>${[16,32,48,80].map((s,j)=>`<image href="${uri('mark-'+theme)}" x="${x+40+j*100}" y="${720-s/2}" width="${s}" height="${s}"/>`).join('')}</g>`
}).join('')
await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="800">${panels}</svg>`)).png().toFile(`${root}../docs/branding/logo-preview.png`)
